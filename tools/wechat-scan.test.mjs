import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { runInNewContext } from 'node:vm';
import test from 'node:test';

const root = new URL('../apps/wechat-mini-program/miniprogram/', import.meta.url);
const now = Date.parse('2026-10-02T04:00:00Z');
const fixture = (changes = {}) => JSON.stringify({
  type: 'NikkiSyncRemoteBridge', version: 1, sessionId: 'A'.repeat(22),
  token: 'B'.repeat(43), expiresAt: new Date(now + 600000).toISOString(),
  endpoint: 'https://192.168.1.2:28950', tlsFingerprintSha256: 'a'.repeat(64), ...changes
});
async function parser() {
  const module = { exports: {} };
  runInNewContext(await readFile(new URL('lib/remote-qr.js', root), 'utf8'), { module });
  return module.exports.parseRemoteQr;
}

test('accepts current PC QR fields without leaking credentials into errors', async () => {
  const parse = await parser();
  const value = parse(fixture(), now);
  assert.equal(value.endpoint, 'https://192.168.1.2:28950');
  assert.equal(value.token.length, 43);
  for (const raw of ['{}', 'not JSON', 'x'.repeat(4097), '[]', 'null']) {
    assert.throws(() => parse(raw, now), /无法识别/);
  }
});

test('parses a QR generated by the real PC RemoteSessionStore', async () => {
  const { RemoteSessionStore } = await import('../apps/pc-companion/dist/src/remote/RemoteSessionStore.js');
  const store = new RemoteSessionStore(() => now);
  const created = store.create([{ resourceId: 'test-resource', sha256: '0'.repeat(64) }], {
    endpoint: 'https://192.168.1.2:28950', tlsFingerprintSha256: 'a'.repeat(64)
  });
  const parse = await parser();
  const parsed = parse(created.qrPayload, now);
  assert.equal(parsed.sessionId, created.sessionId);
  assert.equal(parsed.token, created.token);
  assert.equal(store.authorize(parsed.sessionId, parsed.token).status, 'ok');
  store.closeAll();
});

test('rejects expired or implausibly long sessions and wrong protocol fields', async () => {
  const parse = await parser();
  for (const changes of [
    { expiresAt: new Date(now).toISOString() },
    { expiresAt: new Date(now + 660001).toISOString() },
    { expiresAt: 'tomorrow' }, { version: 2 }, { type: 'Other' },
    { token: 'B'.repeat(42) }, { sessionId: '../bad' },
    { tlsFingerprintSha256: 'not a fingerprint' }, { token: 123 }
  ]) assert.throws(() => parse(fixture(changes), now));
});

test('only accepts canonical private IPv4 HTTPS endpoints', async () => {
  const parse = await parser();
  for (const endpoint of ['https://10.0.0.1', 'https://172.16.0.1:443', 'https://172.31.255.254:65535', 'https://192.168.1.1/']) {
    assert.ok(parse(fixture({ endpoint }), now).endpoint.startsWith('https://'));
  }
  for (const endpoint of ['http://192.168.1.2', 'https://8.8.8.8', 'https://172.32.0.1',
    'https://127.0.0.1', 'https://169.254.1.2', 'https://example.com',
    'https://192.168.1.2@evil.com', 'https://192.168.1.2/path',
    'https://192.168.1.2?token=secret', 'https://192.168.1.2#fragment',
    'https://192.168.01.2', 'https://192.168.1.256', 'https://192.168.1.2:0',
    'https://192.168.1.2:65536', 'https://192.168.1.2:0443', 'https://0xc0a80102']) {
    assert.throws(() => parse(fixture({ endpoint }), now));
  }
});

async function pageFixture() {
  const parse = await parser();
  let page, scan;
  let requestCount = 0;
  runInNewContext(await readFile(new URL('pages/index/index.js', root), 'utf8'), {
    require: () => ({ parseRemoteQr: (raw) => parse(raw, now) }),
    wx: { scanCode: options => { scan = options; }, request: () => { requestCount++; } },
    Page: definition => { page = definition; },
    Date: { now: () => now, parse: Date.parse }
  });
  page.data = JSON.parse(JSON.stringify(page.data));
  page.setData = changes => Object.assign(page.data, changes);
  page.onLoad();
  return { page, scan: () => scan, requests: () => requestCount };
}

test('scan result displays only non-secret diagnostics and never makes an untrusted request', async () => {
  const { page, scan, requests } = await pageFixture();
  page.scanQr();
  assert.equal(scan().scanType[0], 'qrCode');
  scan().success({ result: fixture() });
  assert.equal(page.data.state, 'identified');
  assert.match(page.data.message, /尚未连接/);
  assert.equal(page.data.endpoint, 'https://192.168.1.2:28950');
  assert.ok(!JSON.stringify(page.data).includes('B'.repeat(43)));
  assert.ok(!JSON.stringify(page.data).includes('A'.repeat(22)));
  assert.equal(requests(), 0);
});

test('invalid scan and cancellation clear previous diagnostics', async () => {
  const { page, scan } = await pageFixture();
  page.scanQr(); scan().success({ result: fixture() });
  page.scanQr(); scan().success({ result: fixture({ token: 'SECRET_INVALID_TOKEN' }) });
  assert.equal(page.data.state, 'error');
  assert.equal(page.data.endpoint, '');
  assert.ok(!JSON.stringify(page.data).includes('SECRET_INVALID_TOKEN'));
  page.scanQr(); scan().fail({ errMsg: 'scanCode:fail cancel' });
  assert.equal(page.data.state, 'idle');
});

test('late scan callback after unloading is ignored', async () => {
  const { page, scan } = await pageFixture();
  page.scanQr(); const pending = scan();
  page.onUnload(); pending.success({ result: fixture() });
  assert.notEqual(page.data.state, 'identified');
});

test('returning after QR expiry clears address instead of displaying an active session', async () => {
  const { page, scan } = await pageFixture();
  page.scanQr(); scan().success({ result: fixture({ expiresAt: new Date(now - 1).toISOString() }) });
  assert.equal(page.data.state, 'error');
  page.data.state = 'identified'; page.data.endpoint = 'https://192.168.1.2';
  page._expiresAtMs = now - 1;
  page.onShow();
  assert.equal(page.data.state, 'expired');
  assert.equal(page.data.endpoint, '');
});
