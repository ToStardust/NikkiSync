// Generated third-party notices: mechanical copies, never edit dependency code.
const notices = [];
// npm workspaces may hoist dependencies: resolve installed package directories up the ancestor chain.
function findPackageDirectory(name) {
  let current=base;
  while(true){const directory=resolve(current,'node_modules',name);try{readFileSync(resolve(directory,'package.json'));return directory;}catch{}
    const parent=dirname(current);if(parent===current)return;current=parent;}
}
const pending=['noise-handshake','sodium-javascript','buffer'],visited=new Set();
while(pending.length){
  const name=pending.shift();if(visited.has(name))continue;visited.add(name);
  const packageDir=findPackageDirectory(name);if(!packageDir)throw new Error('Missing dependency license source: '+name);
  const info=JSON.parse(readFileSync(resolve(packageDir,'package.json'),'utf8'));
  pending.push(...Object.keys(info.dependencies||{}));
  const files = readdirSync(packageDir).filter(x => /^licen[sc]e(?:\.|$)/i.test(x)).sort();
  notices.push(`${info.name}@${info.version} — declared license: ${info.license || 'not declared'}\n`
    + (files.length ? files.map(x => readFileSync(resolve(packageDir, x), 'utf8')).join('\n') : 'No license text included in installed package; see upstream repository.'));
}
